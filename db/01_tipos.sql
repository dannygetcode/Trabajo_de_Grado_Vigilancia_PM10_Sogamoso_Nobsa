-- Esquema y tipos enumerados del sistema de vigilancia PM10
CREATE SCHEMA IF NOT EXISTS svca;
SET search_path TO svca;

CREATE TYPE estado_estacion AS ENUM
  ('OPERATIVA', 'EN_MANTENIMIENTO', 'SIN_TRANSMISION', 'INACTIVA');
CREATE TYPE estado_medicion AS ENUM
  ('CRUDO', 'VALIDO', 'SOSPECHOSO', 'INVALIDO',
   'VALIDADO_MANUAL', 'CORREGIDO', 'INVALIDADO');
CREATE TYPE accion_revision AS ENUM ('APROBAR', 'CORREGIR', 'INVALIDAR');
CREATE TYPE nivel_normativo AS ENUM ('PREVENCION', 'ALERTA', 'EMERGENCIA');
CREATE TYPE categoria_ica AS ENUM
  ('BUENA', 'ACEPTABLE', 'DANINA_SENSIBLES', 'DANINA',
   'MUY_DANINA', 'PELIGROSA');
CREATE TYPE origen_declaratoria AS ENUM ('MEDICION', 'PRONOSTICO');
CREATE TYPE estado_declaratoria AS ENUM
  ('PROPUESTA', 'CONFIRMADA', 'DESCARTADA', 'CERRADA');
CREATE TYPE estado_version AS ENUM ('REGISTRADA', 'ACTIVA', 'RETIRADA');
CREATE TYPE estado_ejecucion AS ENUM
  ('EN_CURSO', 'EXITOSA', 'PARCIAL', 'FALLIDA');
CREATE TYPE estado_pronostico AS ENUM
  ('EMITIDO', 'EN_SEGUIMIENTO', 'EVALUADO', 'INCOMPLETO');
CREATE TYPE estado_notificacion AS ENUM
  ('PENDIENTE', 'ENVIADA', 'EN_REINTENTO', 'FALLIDA');
CREATE TYPE estado_informe AS ENUM
  ('EN_GENERACION', 'GENERADO', 'APROBADO', 'DEVUELTO');
CREATE TYPE estado_usuario AS ENUM ('ACTIVO', 'BLOQUEADO', 'INACTIVO');
CREATE TYPE estado_escenario AS ENUM
  ('CONFIGURADO', 'EN_EJECUCION', 'PAUSADO', 'FINALIZADO');
CREATE TYPE tipo_falla AS ENUM
  ('FUERA_DE_RANGO', 'VALOR_REPETIDO', 'CAMBIO_BRUSCO', 'AUSENCIA_DE_DATO');
CREATE TYPE estado_falla AS ENUM
  ('PROGRAMADA', 'INYECTADA', 'DETECTADA', 'NO_DETECTADA');
